#!/bin/bash
set -e

echoAutoGeneratedComments()
{
  echo "# ---------------------------------------------------"
  echo "# ----- config.yml ----------------------------------"
  echo "# ----- GENERATED CODE - DO NOT MODIFY BY HAND ------"
  echo "# ---------------------------------------------------"
  echo ""
}

for dependency in yq python3
do
  if ! command -v "$dependency" &> /dev/null
  then
      echo "$dependency command could not be found"
      echo "  yq:      https://github.com/mikefarah/yq  (brew install yq / apt install yq)"
      echo "  python3: https://www.python.org/downloads/"
      exit 1
  fi
done

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

# Pack one FYAML directory into a yaml config file.
#   $1 = FYAML source directory, $2 = destination file
pack()
{
  local source="$1"
  local destination="$2"
  local packed

  packed=$(python3 "$SCRIPT_DIR/fyaml_pack.py" "$source" | yq --input-format=json --output-format=yaml --indent=4)

  # printf, not echo: the packed yaml contains backslash escapes inside
  # double-quoted scalars, and echo expands those under a POSIX shell.
  {
    echoAutoGeneratedComments
    printf '%s\n\n' "$packed"
  } > "$destination"
}

echo "Changing directory to circleci_config..."
cd "$SCRIPT_DIR/.." || exit 1

echo ""
echo "Replacing current .circleci/config.yml file..."
pack config-setup ../.circleci/config.yml

echo ""
echo "Replacing current .circleci/continue-config.yml file..."
pack config-continuation ../.circleci/continue-config.yml

cd ..

# Both generated files must still be valid yaml.
for generated in .circleci/config.yml .circleci/continue-config.yml
do
  if ! yq --exit-status '.' "$generated" > /dev/null 2>&1
  then
    echo "ERROR: $generated is not valid yaml"
    exit 1
  fi
done

echo "Done!"
