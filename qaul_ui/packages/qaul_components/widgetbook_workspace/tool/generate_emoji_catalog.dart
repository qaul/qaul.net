// Regenerates lib/support/emoji_catalog.dart from Unicode's emoji-test.txt.
//
// Usage (from widgetbook_workspace/):
//   curl -o /tmp/emoji-test.txt https://unicode.org/Public/emoji/latest/emoji-test.txt
//   dart run tool/generate_emoji_catalog.dart /tmp/emoji-test.txt
import 'dart:io';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'usage: dart run tool/generate_emoji_catalog.dart <emoji-test.txt>',
    );
    exit(64);
  }

  final lines = File(args.single).readAsLinesSync();
  final version = lines
      .firstWhere((l) => l.startsWith('# Version:'))
      .split(':')
      .last
      .trim();

  final groups = <String, List<String>>{};
  String? group;
  final entry = RegExp(
    r'^[0-9A-F ]+; fully-qualified\s+# (\S+) E(\d+\.\d+) (.+)$',
  );
  for (final line in lines) {
    if (line.startsWith('# group:')) {
      group = line.substring('# group:'.length).trim();
      groups[group] = [];
      continue;
    }
    final match = entry.firstMatch(line);
    if (match == null || group == null) continue;
    final emoji = match.group(1)!;
    final since = match.group(2)!;
    final name = match.group(3)!.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
    groups[group]!.add("    ('$emoji', '$name', '$since'),");
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_emoji_catalog.dart from Unicode')
    ..writeln('// emoji-test.txt v$version. Do not edit by hand.')
    ..writeln()
    ..writeln(
      '/// One fully-qualified emoji: the glyph, its CLDR name, and the',
    )
    ..writeln('/// Emoji version that introduced it.')
    ..writeln(
      'typedef EmojiCatalogEntry = (String emoji, String name, String since);',
    )
    ..writeln()
    ..writeln("const String kEmojiCatalogUnicodeVersion = '$version';")
    ..writeln()
    ..writeln('/// Every fully-qualified emoji, grouped as in emoji-test.txt.')
    ..writeln('const Map<String, List<EmojiCatalogEntry>> kEmojiCatalog = {');
  for (final MapEntry(:key, :value) in groups.entries) {
    if (value.isEmpty) continue;
    out
      ..writeln("  '$key': [")
      ..writeAll(value, '\n')
      ..writeln()
      ..writeln('  ],');
  }
  out.writeln('};');

  File('lib/support/emoji_catalog.dart').writeAsStringSync(out.toString());
  final total = groups.values.fold<int>(0, (sum, g) => sum + g.length);
  stdout.writeln(
    'Wrote $total emoji in ${groups.length} groups (Unicode $version).',
  );
}
